package main

import (
	"fmt"
	"go/format"
	"go/types"
	"strings"
	"unicode"

	. "github.com/dave/jennifer/jen"
)

const (
	flagsPFlag = "pflag"
	flagsStd   = "std"
	flagsNone  = "none"
)

const (
	pkgCfg   = "github.com/USA-RedDragon/configulator/v2"
	pkgPFlag = "github.com/USA-RedDragon/configulator/v2/flags/pflag"
	pfl      = "github.com/spf13/pflag"
)

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

type emitter struct {
	m            *Model
	f            *File
	shadows      map[string]bool // shadow name -> already emitted
	shadowOrder  []string        // emission order, for the fast paths
	shadowFields map[string][]*Field
	needQuoteKey bool
}

// quoteKeyName returns the name of the helper that quotes map keys in
// origin paths. The helper is written into each generated file instead of
// being exported from the runtime, since it's only formatting.
func (e *emitter) quoteKeyName() string {
	e.needQuoteKey = true
	return lowerFirst(e.m.TypeName) + "QuoteKey"
}

func emit(m *Model, flagsMode string) ([]byte, error) {
	e := &emitter{
		m: m, f: NewFilePathName(m.PkgPath, m.PkgName),
		shadows:      map[string]bool{},
		shadowFields: map[string][]*Field{},
	}
	e.f.HeaderComment("Code generated by configulator. DO NOT EDIT.")
	e.f.HeaderComment("")
	e.f.HeaderComment("//go:build goexperiment.jsonv2")
	e.f.ImportName(pkgCfg, "configulator")
	e.f.ImportAlias(pkgCfg, "configulator")
	e.f.ImportAlias(pkgPFlag, "cpflag")
	e.f.ImportName(pfl, "pflag")

	e.emitShadowStruct(shadowName(m.TypeName), m.Fields)
	e.emitSchemaCtor()
	e.emitApplyDefaults()
	e.emitDecodeFile()
	e.emitApplyTo(shadowName(m.TypeName), m.Fields, "")
	e.emitApplyEnv()
	switch flagsMode {
	case flagsPFlag:
		e.emitPFlagHooks()
	case flagsStd:
		e.emitStdFlagHooks()
	}
	e.emitFastPaths()
	e.emitPrintConfig()
	if e.needQuoteKey {
		e.f.Func().Id(e.quoteKeyName()).Params(Id("k").String()).String().Block(
			For(List(Id("_"), Id("c")).Op(":=").Range().Id("k")).Block(
				If(Id("c").Op("==").LitRune('.').Op("||").Id("c").Op("==").LitRune('[')).Block(
					Return(Lit(`"`).Op("+").Id("k").Op("+").Lit(`"`)),
				),
			),
			Return(Id("k")),
		)
	}

	src := []byte(fmt.Sprintf("%#v", e.f))
	return format.Source(src)
}

func shadowName(typeName string) string { return lowerFirst(typeName) + "Shadow" }

func (e *emitter) shadowFor(t types.Type) string {
	named, ok := t.(*types.Named)
	if !ok {
		panic("shadowFor: not a named type")
	}
	return shadowName(named.Obj().Name())
}

// goName returns the shadow field name: the last element of a promoted
// Go path.
func goName(f *Field) string {
	parts := strings.Split(f.GoName, ".")
	return parts[len(parts)-1]
}

// cfgSel renders recv followed by the field's Go path, which may be
// promoted.
func cfgSel(recv string, f *Field) *Statement {
	s := Id(recv)
	for _, p := range strings.Split(f.GoName, ".") {
		s = s.Dot(p)
	}
	return s
}

func (e *emitter) emitSchemaCtor() {
	n := e.m.TypeName
	d := Dict{
		Id("ApplyDefaults"): Id(lowerFirst(n) + "ApplyDefaults"),
		Id("DecodeFile"):    Id(lowerFirst(n) + "DecodeFile"),
		Id("ApplyEnv"):      Id(lowerFirst(n) + "ApplyEnv"),
	}
	if req := requiredPaths(e.m.Fields, ""); len(req) > 0 {
		lits := make([]Code, 0, len(req))
		for _, p := range req {
			lits = append(lits, Lit(p))
		}
		d[Id("Required")] = Index().String().Values(lits...)
	}
	e.f.Comment(fmt.Sprintf("%sSchema returns the generated schema for %s.", n, n))
	e.f.Func().Id(n+"Schema").Params().Op("*").Qual(pkgCfg, "Schema").Index(Id(n)).Block(
		Return(Op("&").Qual(pkgCfg, "Schema").Index(Id(n)).Values(d)),
	)
}

// requiredPaths collects dotted paths of required:"true" fields.
func requiredPaths(fields []*Field, prefix string) []string {
	var out []string
	for _, f := range fields {
		p := joinPath(prefix, f.Tag)
		if f.Required {
			out = append(out, p)
		}
		if f.Kind == KindStruct {
			out = append(out, requiredPaths(f.Fields, p)...)
		}
	}
	return out
}
